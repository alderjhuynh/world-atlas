#!/usr/bin/env node

const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const DATA_DIR = path.join(ROOT, "js", "data");
const CONFIG_FILE = path.join(ROOT, "js", "config.js");
const INDEX_FILE = path.join(DATA_DIR, "index.js");
const CNAME_FILE = path.join(ROOT, "CNAME");

const SUMMARY_MAX_LEN = 200;

function collectEntryFiles(dir) {
  const files = [];
  for (const name of fs.readdirSync(dir)) {
    const full = path.join(dir, name);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) {
      files.push(...collectEntryFiles(full));
    } else if (name.endsWith(".js") && !name.startsWith("_") && name !== "index.js") {
      files.push(full);
    }
  }
  return files.sort();
}

function loadWorldData() {
  const sandbox = { window: {}, console };
  vm.createContext(sandbox);

  const filesToRun = [CONFIG_FILE, INDEX_FILE, ...collectEntryFiles(DATA_DIR)];
  for (const file of filesToRun) {
    const code = fs.readFileSync(file, "utf8");
    vm.runInContext(code, sandbox, { filename: file });
  }

  return {
    config: sandbox.window.WORLD_CONFIG,
    data: sandbox.window.WORLD_DATA || {},
  };
}

function escapeHtml(str) {
  return String(str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

function truncate(str, maxLen) {
  if (!str || str.length <= maxLen) return str || "";
  return str.slice(0, maxLen - 1).trimEnd() + "…";
}

function getSiteUrl() {
  if (fs.existsSync(CNAME_FILE)) {
    const host = fs.readFileSync(CNAME_FILE, "utf8").trim();
    if (host) return `https://${host}`;
  }
  return null; // fall back to relative URLs if there's no custom domain configured
}

function absoluteOrRelative(siteUrl, relativePath) {
  return siteUrl ? `${siteUrl}/${relativePath}` : `/${relativePath}`;
}

function renderPage({ entry, collection, siteName, siteUrl, redirectTarget }) {
  const title = escapeHtml(entry.title);
  const description = escapeHtml(truncate(entry.summary, SUMMARY_MAX_LEN));
  const pageUrl = absoluteOrRelative(siteUrl, `${collection.key}/${entry.id}.html`);
  const canonicalUrl = absoluteOrRelative(siteUrl, redirectTarget);
  const imageTag = entry.coverImage
    ? `<meta property="og:image" content="${escapeHtml(absoluteOrRelative(siteUrl, entry.coverImage))}">\n<meta name="twitter:card" content="summary_large_image">`
    : `<meta name="twitter:card" content="summary">`;

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}: ${escapeHtml(siteName)}</title>

<!-- Auto-generated by scripts/generate-og-pages.js — do not edit by hand.
     Re-run the script after changing this entry's data instead. -->

<meta property="og:type" content="article">
<meta property="og:site_name" content="${escapeHtml(siteName)}">
<meta property="og:title" content="${title}">
<meta property="og:description" content="${description}">
<meta property="og:url" content="${escapeHtml(pageUrl)}">
${imageTag}

<link rel="canonical" href="${escapeHtml(canonicalUrl)}">
<meta http-equiv="refresh" content="0; url=../${redirectTarget}">
<script>location.replace("../${redirectTarget}");</script>
</head>
<body>
<p>Redirecting to <a href="../${redirectTarget}">${title}</a>…</p>
</body>
</html>
`;
}

function main() {
  const { config, data } = loadWorldData();
  if (!config) {
    console.error("Could not load WORLD_CONFIG from js/config.js");
    process.exit(1);
  }

  const siteUrl = getSiteUrl();
  if (!siteUrl) {
    console.log("No CNAME file found — og:url/og:image will use relative paths.");
  }

  let written = 0;

  for (const collection of config.collections || []) {
    const entries = data[collection.key] || [];
    if (entries.length === 0) continue;

    const outDir = path.join(ROOT, collection.key);
    fs.mkdirSync(outDir, { recursive: true });

    for (const entry of entries) {
      const redirectTarget = `entry.html?c=${encodeURIComponent(collection.key)}&id=${encodeURIComponent(entry.id)}`;
      const html = renderPage({ entry, collection, siteName: config.siteName, siteUrl, redirectTarget });

      const outFile = path.join(outDir, `${entry.id}.html`);
      fs.writeFileSync(outFile, html);
      written++;
      console.log(`WROTE ${path.relative(ROOT, outFile)}`);
    }
  }

  console.log();
  console.log(`Done. Generated ${written} preview page(s).`);
  console.log(`Share links like: <site>/<collection-key>/<entry-id>.html`);
}

main();